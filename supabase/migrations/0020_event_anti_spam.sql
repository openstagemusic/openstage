-- 0020 — Anti-spam: il tetto conta i tentativi, e un account si può fermare.
--
-- Perché un registro a parte invece di un conteggio su `events`: il proprietario
-- può cancellare la propria bozza (`events_delete_own`), quindi un conteggio
-- sulle righe si azzera con elimina-e-ricrea. Il registro è scritto **solo dal
-- database**, è append-only e vive più dell'evento: la quota non torna indietro.
--
-- Tutto qui è l'autorità: chi parla direttamente con l'API passa dagli stessi
-- trigger. L'admin e il servizio (migrazioni, manutenzione) restano fuori dal
-- tetto, così un intervento dell'amministratore non viene mai bloccato.

-- --- Il tetto e la sospensione vivono sul profilo ---------------------------

alter table public.profiles
  add column if not exists events_daily_limit integer,
  add column if not exists suspended_at timestamptz;

comment on column public.profiles.events_daily_limit is
  'Tetto di serate nelle 24 ore per questo account. Vuoto = 10.';
comment on column public.profiles.suspended_at is
  'Account sospeso: il database rifiuta creazione e modifica delle sue serate.';

-- --- Il registro dei tentativi riusciti -------------------------------------

create table if not exists public.event_creations (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  event_id uuid references public.events(id) on delete set null,
  created_at timestamptz not null default now()
);

comment on table public.event_creations is
  'Registro delle serate davvero create: serve alla quota anti-spam e non si cancella con l''evento.';

create index if not exists event_creations_window_idx
  on public.event_creations (profile_id, created_at desc);

alter table public.event_creations enable row level security;

-- Nessuno scrive qui: ci scrive il trigger, con i privilegi del proprietario.
-- L'admin può leggerlo (serve al pannello di moderazione, B40).
drop policy if exists event_creations_read_admin on public.event_creations;
create policy event_creations_read_admin on public.event_creations
  for select using (public.is_admin());

-- --- Quante serate al giorno per questo account -----------------------------

create or replace function public.event_daily_limit(p_profile uuid)
returns integer
language sql
stable
security definer
set search_path to 'public', 'pg_temp'
as $$
  -- Un valore, non una costante nel codice: l'admin lo cambia su un account
  -- senza deploy, e la fiducia a scalini (B40) sarà un altro valore qui.
  select coalesce(
    (select p.events_daily_limit from public.profiles p where p.id = p_profile),
    10
  );
$$;

revoke all on function public.event_daily_limit(uuid) from public, anon, authenticated;

-- --- Il controllo, prima che la serata entri ---------------------------------

create or replace function public.events_rate_limit()
returns trigger
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
declare
  v_used integer;
  v_limit integer;
begin
  -- L'admin e il servizio (auth.uid() assente) non hanno quota.
  if new.created_by is null or auth.uid() is null or public.is_admin() then
    return new;
  end if;

  select count(*) into v_used
    from public.event_creations c
   where c.profile_id = new.created_by
     and c.created_at > now() - interval '24 hours';

  v_limit := public.event_daily_limit(new.created_by);

  if v_used >= v_limit then
    raise exception 'Troppe serate nelle ultime 24 ore per questo account'
      using errcode = 'OS429',
            detail = format('create: %s, tetto: %s', v_used, v_limit);
  end if;

  return new;
end;
$$;

revoke all on function public.events_rate_limit() from public, anon, authenticated;

drop trigger if exists events_rate_limit on public.events;
create trigger events_rate_limit
  before insert on public.events
  for each row execute function public.events_rate_limit();

-- --- La serata è entrata: si segna (dopo, così si segna solo ciò che esiste) --

create or replace function public.events_log_creation()
returns trigger
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
begin
  if new.created_by is not null then
    insert into public.event_creations (profile_id, event_id)
    values (new.created_by, new.id);
  end if;

  return null;
end;
$$;

revoke all on function public.events_log_creation() from public, anon, authenticated;

drop trigger if exists events_log_creation on public.events;
create trigger events_log_creation
  after insert on public.events
  for each row execute function public.events_log_creation();

-- --- Un account sospeso non scrive e non modifica ----------------------------

create or replace function public.events_block_suspended()
returns trigger
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $$
begin
  if auth.uid() is null or public.is_admin() or new.created_by is null then
    return new;
  end if;

  if exists (
    select 1 from public.profiles p
     where p.id = new.created_by and p.suspended_at is not null
  ) then
    raise exception 'Account sospeso' using errcode = 'OS403';
  end if;

  return new;
end;
$$;

revoke all on function public.events_block_suspended() from public, anon, authenticated;

drop trigger if exists events_block_suspended on public.events;
create trigger events_block_suspended
  before insert or update on public.events
  for each row execute function public.events_block_suspended();
