-- --- Trigger: bozze da revisione --------------------------------------------

create or replace function public.telegram_on_review_draft()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
begin
  if new.status = 'draft'
     and not exists (
       select 1 from public.profiles p
       where p.id = new.created_by and p.verified_at is not null
     )
     and not exists (
       select 1 from public.venues v
       join public.profiles p on p.id = v.profile_id
       where v.id = new.venue_id and p.verified_at is not null
     )
     and not exists (
       select 1 from public.artists a
       join public.profiles p on p.id = a.profile_id
       where a.id = new.artist_id and p.verified_at is not null
     ) then
    perform public.notify_admin_telegram(
      '📝 Nuovo evento in bozza da revisione.' || chr(10) ||
      'https://getopenstage.it/it/admin/bozze',
      'draft:' || new.id::text
    );
  end if;

  return null;
end;
$fn$;

revoke all on function public.telegram_on_review_draft() from public;
drop trigger if exists telegram_on_review_draft on public.events;
create trigger telegram_on_review_draft
  after insert on public.events
  for each row execute function public.telegram_on_review_draft();

-- --- Trigger: email fallite --------------------------------------------------

create or replace function public.telegram_on_email_failed()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
begin
  if new.status = 'failed' and old.status is distinct from 'failed' then
    perform public.notify_admin_telegram(
      '⚠️ Una email non è stata inviata.' || chr(10) ||
      'https://getopenstage.it/it/admin',
      'email-failed:' || new.id::text || ':' || new.attempts::text
    );
  end if;

  return null;
end;
$fn$;

revoke all on function public.telegram_on_email_failed() from public;
drop trigger if exists telegram_on_email_failed on public.email_queue;
create trigger telegram_on_email_failed
  after update on public.email_queue
  for each row execute function public.telegram_on_email_failed();
