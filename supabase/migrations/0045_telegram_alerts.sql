-- ============================================================================
-- OpenStage — Fase 8.6 (avvisi Telegram in tempo reale)
-- Le code della control room avvisano l'admin su Telegram quando arriva
-- qualcosa da fare. Il bot e la chat stanno in Supabase Vault, mai nel codice.
--
-- Regole:
-- - nessun dato personale nel messaggio: solo tipo di evento e link;
-- - un solo avviso per evento (dedupe_key);
-- - se il bot non è configurato, tutto resta silenzioso;
-- - l'invio è asincrono con pg_net, non blocca la scrittura.
--
-- Idempotente.
-- ============================================================================

create table if not exists public.telegram_alert_log (
  id bigint generated by default as identity primary key,
  dedupe_key text not null unique,
  message text not null,
  created_at timestamptz not null default now()
);

alter table public.telegram_alert_log enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public' and tablename = 'telegram_alert_log'
      and policyname = 'telegram_alert_log_select_admin'
  ) then
    create policy telegram_alert_log_select_admin on public.telegram_alert_log
      for select using ((select public.is_admin()));
  end if;
end $$;

create or replace function public.admin_telegram_configured()
returns boolean
language plpgsql
security definer
set search_path = public, vault, pg_temp
as $fn$
begin
  if not public.is_admin() then
    raise exception 'Solo l''amministratore può vedere questa impostazione' using errcode = '42501';
  end if;

  return exists (select 1 from vault.decrypted_secrets where name = 'telegram_bot_token')
     and exists (select 1 from vault.decrypted_secrets where name = 'telegram_admin_chat_id');
end;
$fn$;

revoke all on function public.admin_telegram_configured() from public;
grant execute on function public.admin_telegram_configured() to authenticated;

create or replace function public.notify_admin_telegram(
  p_text text,
  p_dedupe_key text
)
returns void
language plpgsql
security definer
set search_path = public, vault, net, pg_temp
as $fn$
declare
  v_token text;
  v_chat text;
  v_inserted boolean := false;
begin
  if p_text is null or btrim(p_text) = '' then
    return;
  end if;

  select decrypted_secret into v_token
    from vault.decrypted_secrets where name = 'telegram_bot_token' limit 1;
  select decrypted_secret into v_chat
    from vault.decrypted_secrets where name = 'telegram_admin_chat_id' limit 1;

  if v_token is null or v_chat is null then
    return;
  end if;

  if p_dedupe_key is not null then
    insert into public.telegram_alert_log (dedupe_key, message)
    values (p_dedupe_key, p_text)
    on conflict (dedupe_key) do nothing;

    get diagnostics v_inserted = row_count;
    if not v_inserted then
      return;
    end if;
  end if;

  -- Telegram non è raggiungibile direttamente da Supabase in modo affidabile:
  -- la richiesta passa dalla rotta Vercel, che ha il token e la chat.
  perform net.http_post(
    url := 'https://getopenstage.it/api/admin/telegram/alert',
    body := jsonb_build_object('text', p_text),
    params := '{}'::jsonb,
    headers := jsonb_build_object(
      'Content-Type', 'application/json',
      'x-telegram-secret', v_token
    ),
    timeout_milliseconds := 10000
  );
end;
$fn$;

revoke all on function public.notify_admin_telegram(text, text) from public, anon, authenticated;

-- --- Trigger: nuovi ticket ---------------------------------------------------

create or replace function public.telegram_on_contact_message()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
begin
  perform public.notify_admin_telegram(
    '🔔 Nuovo ticket dal form contatti.' || chr(10) ||
    'https://getopenstage.it/it/admin/messaggi',
    'ticket:' || new.id::text
  );
  return null;
end;
$fn$;

revoke all on function public.telegram_on_contact_message() from public;
drop trigger if exists telegram_on_contact_message on public.contact_messages;
create trigger telegram_on_contact_message
  after insert on public.contact_messages
  for each row execute function public.telegram_on_contact_message();

-- --- Trigger: richieste locali e claim approvati ------------------------------

create or replace function public.telegram_on_claim()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $fn$
begin
  if tg_op = 'INSERT' and new.status = 'pending' then
    perform public.notify_admin_telegram(
      '🔔 Nuova richiesta per una scheda locale.' || chr(10) ||
      'https://getopenstage.it/it/admin/claim',
      'claim:' || new.id::text
    );
  elsif tg_op = 'UPDATE' and new.status = 'approved' and old.status is distinct from 'approved' then
    perform public.notify_admin_telegram(
      '✅ Scheda reclamata: da verificare.' || chr(10) ||
      'https://getopenstage.it/it/admin/claim',
      'claim-approved:' || new.id::text
    );
  end if;

  return null;
end;
$fn$;

revoke all on function public.telegram_on_claim() from public;
drop trigger if exists telegram_on_claim on public.claims;
create trigger telegram_on_claim
  after insert or update on public.claims
  for each row execute function public.telegram_on_claim();

